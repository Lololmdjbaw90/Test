// Writes native/Sugerly/App/ModerationLexicon.swift from
// src/lib/moderationLexicon.json, so the app and the website moderate with
// the same word lists. Run after editing the JSON:
//   node scripts/gen-moderation.mjs
import { readFileSync, writeFileSync } from "node:fs";

const lex = JSON.parse(readFileSync("src/lib/moderationLexicon.json", "utf8"));
const str = (s) => JSON.stringify(s); // JSON strings are valid Swift string literals for our characters
const raw = (s) => `#"${s}"#`;
const num = (n) => (Number.isInteger(n) ? `${n}.0` : String(n));
const dict = (obj, indent) => {
  const rows = Object.entries(obj).map(([k, v]) => `${indent}    ${str(k)}: ${num(v)},`);
  return rows.length ? `[\n${rows.join("\n")}\n${indent}]` : "[:]";
};
const nested = (obj) => `[\n${Object.entries(obj).map(([k, v]) => `        ${str(k)}: ${dict(v, "        ")},`).join("\n")}\n    ]`;
const list = (arr) => `[${arr.map(str).join(", ")}]`;

const swift = `// Generated by scripts/gen-moderation.mjs from src/lib/moderationLexicon.json.
// Edit the JSON (shared with the website), not this file.
import Foundation

enum ModerationLexicon {
    static let terms: [String: [String: Double]] = ${nested(lex.terms)}

    static let compact: [String] = ${list(lex.compact)}

    static let allow: Set<String> = ${list(lex.allow)}

    static let phrases: [String: [String: Double]] = ${nested(lex.phrases)}

    static let patterns: [String: [(String, Double)]] = [
${Object.entries(lex.patterns).map(([k, v]) => `        ${str(k)}: [\n${v.map(([p, w]) => `            (${raw(p)}, ${num(w)}),`).join("\n")}\n        ],`).join("\n")}
    ]

    static let secondPerson: Set<String> = ${list(lex.secondPerson)}

    static let safeDomains: [String] = ${list(lex.safeDomains)}

    static let shorteners: [String] = ${list(lex.shorteners)}

    static let invites: [String] = ${list(lex.invites)}

    static let reasons: [String: String] = [
${Object.entries(lex.reasons).map(([k, v]) => `        ${str(k)}: ${str(v)},`).join("\n")}
    ]
}
`;
writeFileSync("native/Sugerly/App/ModerationLexicon.swift", swift);
console.log("Wrote native/Sugerly/App/ModerationLexicon.swift");
